// WithHealthEndpointAt returns a ServeMuxOption that will add an endpoint to the created ServeMux at the path specified by endpointPath.
// When called the handler will forward the request to the upstream grpc service health check (defined in the
// gRPC Health Checking Protocol).
//
// See here https://grpc-ecosystem.github.io/grpc-gateway/docs/operations/health_check/ for more information on how
// to setup the protocol in the grpc server.
//
// If you define a service as query parameter, this will also be forwarded as service in the HealthCheckRequest.
func WithHealthEndpointAt(healthCheckClient grpc_health_v1.HealthClient, endpointPath string) ServeMuxOption {
	return func(s *ServeMux) {
		// error can be ignored since pattern is definitely valid
		_ = s.HandlePath(
			http.MethodGet, endpointPath, func(w http.ResponseWriter, r *http.Request, _ map[string]string,
			) {
				_, outboundMarshaler := MarshalerForRequest(s, r)
				annotatedContext, err := AnnotateContext(r.Context(), s, r, grpc_health_v1.Health_Check_FullMethodName, WithHTTPPathPattern(endpointPath))
				if err != nil {
					s.cfg.errorHandler(r.Context(), s, outboundMarshaler, w, r, err)
					return
				}

				var md ServerMetadata
				resp, err := healthCheckClient.Check(annotatedContext, &grpc_health_v1.HealthCheckRequest{
					Service: r.URL.Query().Get("service"),
				}, grpc.Header(&md.HeaderMD), grpc.Trailer(&md.TrailerMD))
				annotatedContext = NewServerMetadataContext(annotatedContext, md)
				if err != nil {
					s.cfg.errorHandler(annotatedContext, s, outboundMarshaler, w, r, err)
					return
				}

				w.Header().Set("Content-Type", "application/json")

				if resp.GetStatus() != grpc_health_v1.HealthCheckResponse_SERVING {
					switch resp.GetStatus() {
					case grpc_health_v1.HealthCheckResponse_NOT_SERVING, grpc_health_v1.HealthCheckResponse_UNKNOWN:
						err = status.Error(codes.Unavailable, resp.String())
					case grpc_health_v1.HealthCheckResponse_SERVICE_UNKNOWN:
						err = status.Error(codes.NotFound, resp.String())
					}

					s.cfg.errorHandler(annotatedContext, s, outboundMarshaler, w, r, err)
					return
				}

				_ = outboundMarshaler.NewEncoder(w).Encode(resp)
			})
	}
}

// WithHealthzEndpoint returns a ServeMuxOption that will add a /healthz endpoint to the created ServeMux.
//
// See WithHealthEndpointAt for the general implementation.
func WithHealthzEndpoint(healthCheckClient grpc_health_v1.HealthClient) ServeMuxOption {
	return WithHealthEndpointAt(healthCheckClient, "/healthz")
}

// NewServeMux returns a new ServeMux whose internal mapping is empty.
//
// All options are resolved once here and the result is frozen into an
// immutable snapshot shared by every request. The same set of options yields
// the same gateway no matter the declaration order (list options keep append
// semantics). Two options that cannot take effect together (for example
// WithUnescapingMode declared twice with different values) make NewServeMux
// panic, with an error naming the two conflicting options: a failed
// construction returns no ServeMux and leaves no observable partial routes.
func NewServeMux(opts ...ServeMuxOption) *ServeMux {
	serveMux := &ServeMux{
		handlers:               make(map[string][]handler),
		forwardResponseOptions: make([]func(context.Context, http.ResponseWriter, proto.Message) error, 0),
		marshalers:             makeMarshalerMIMERegistry(),
		cfg:                    &muxConfig{unescapingMode: UnescapingModeDefault},
		declared:               make(map[muxOptionSlot]string),
	}

	// A conflicting declaration panics while "serveMux" is still a local
	// value: nothing has returned it, and routes registered by earlier
	// options (for example WithHealthEndpointAt) live only on the abandoned
	// mux, so no half-initialized gateway escapes and no partial route set is
	// observable.
	for _, opt := range opts {
		opt(serveMux)
	}

	// Fill the default hooks and freeze the resolved snapshot before any
	// request can observe the mux.
	serveMux.freeze()

	// Options such as WithHealthEndpointAt register handlers while the options
	// are still being applied, so they were wrapped with only the middlewares
	// configured before them. Rewrap them now that all middlewares are known.
	if len(serveMux.middlewares) > 0 {
		chain := chainMiddlewares(serveMux.middlewares)
		for _, handlers := range serveMux.handlers {
			for i := range handlers {
				handlers[i].h = chain(handlers[i].raw)
			}
		}
	}

	return serveMux
}

// Handle associates "h" to the pair of HTTP method and path pattern.
func (s *ServeMux) Handle(meth string, pat Pattern, h HandlerFunc) {
	raw := h
	if len(s.middlewares) > 0 {
		h = chainMiddlewares(s.middlewares)(h)
	}
	s.handlers[meth] = append([]handler{{pat: pat, h: h, raw: raw}}, s.handlers[meth]...)
}

// HandlePath allows users to configure custom path handlers.
// refer: https://grpc-ecosystem.github.io/grpc-gateway/docs/operations/inject_router/
func (s *ServeMux) HandlePath(meth string, pathPattern string, h HandlerFunc) error {
	compiler, err := httprule.Parse(pathPattern)
	if err != nil {
		return fmt.Errorf("parsing path pattern: %w", err)
	}
	tp := compiler.Compile()
	pattern, err := NewPattern(tp.Version, tp.OpCodes, tp.Pool, tp.Verb)
	if err != nil {
		return fmt.Errorf("creating new pattern: %w", err)
	}
	s.Handle(meth, pattern, h)
	return nil
}

// ServeHTTP dispatches the request to the first handler whose pattern matches to r.Method and r.URL.Path.
func (s *ServeMux) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	ctx := r.Context()

	path := r.URL.Path
	if !strings.HasPrefix(path, "/") {
		_, outboundMarshaler := MarshalerForRequest(s, r)
		s.cfg.routingErrorHandler(ctx, s, outboundMarshaler, w, r, http.StatusBadRequest)
		return
	}

	// TODO(v3): remove UnescapingModeLegacy
	unescapingMode := s.cfg.unescapingMode
	if unescapingMode != UnescapingModeLegacy {
		if r.URL.RawPath != "" {
			path = r.URL.RawPath
		} else {
			// net/url only sets RawPath when the request path is not in its
			// default encoding. Without it, Path is all there is and it has
			// already been unescaped once, so unescaping it again while matching
			// would decode a sequence like %252F twice.
			unescapingMode = UnescapingModeLegacy
		}
	}

	// X-HTTP-Method-Override availability is decided by its own switch
	// (methodOverrideAllowed) and never by the path-length-fallback switch,
	// so disabling the fallback cannot make the override silently
	// unavailable.
	if override := r.Header.Get("X-HTTP-Method-Override"); override != "" && s.cfg.methodOverrideAllowed(r) {
		if err := r.ParseForm(); err != nil {
			_, outboundMarshaler := MarshalerForRequest(s, r)
			sterr := status.Error(codes.InvalidArgument, err.Error())
			s.cfg.errorHandler(ctx, s, outboundMarshaler, w, r, sterr)
			return
		}
		r.Method = strings.ToUpper(override)
	}

	var pathComponents []string
	// since in UnescapeModeLegacy, the URL will already have been fully unescaped, if we also split on "%2F"
	// in this escaping mode we would be double unescaping but in UnescapingModeAllCharacters, we still do as the
	// path is the RawPath (i.e. unescaped). That does mean that the behavior of this function will change its default
	// behavior when the UnescapingModeDefault gets changed from UnescapingModeLegacy to UnescapingModeAllExceptReserved
	if unescapingMode == UnescapingModeAllCharacters {
		pathComponents = encodedPathSplitter.Split(path[1:], -1)
	} else {
		pathComponents = strings.Split(path[1:], "/")
	}

	lastPathComponent := pathComponents[len(pathComponents)-1]

	for _, h := range s.handlers[r.Method] {
		// If the pattern has a verb, explicitly look for a suffix in the last
		// component that matches a colon plus the verb. This allows us to
		// handle some cases that otherwise can't be correctly handled by the
		// former LastIndex case, such as when the verb literal itself contains
		// a colon. This should work for all cases that have run through the
		// parser because we know what verb we're looking for, however, there
		// are still some cases that the parser itself cannot disambiguate. See
		// the comment there if interested.

		var verb string
		patVerb := h.pat.Verb()

		idx := -1
		if patVerb != "" && strings.HasSuffix(lastPathComponent, ":"+patVerb) {
			idx = len(lastPathComponent) - len(patVerb) - 1
		}
		if idx == 0 {
			// The last component is the bare verb with nothing before it,
			// which this pattern cannot match. Other patterns still might, so
			// move on rather than ending the search with a 404.
			continue
		}

		// Only copy the components when the verb has to be split off the last
		// one. MatchAndEscape never mutates its input, so sharing the slice
		// across handlers is safe, and copying it per handler otherwise costs
		// len(pathComponents) allocations for every registered pattern.
		comps := pathComponents
		if idx > 0 {
			comps = make([]string, len(pathComponents))
			copy(comps, pathComponents)
			comps[len(comps)-1], verb = lastPathComponent[:idx], lastPathComponent[idx+1:]
		}

		pathParams, err := h.pat.matchAndEscape(comps, verb, unescapingMode, s.cfg.strictDeepWildcard)
		if err != nil {
			var mse MalformedSequenceError
			if ok := errors.As(err, &mse); ok {
				_, outboundMarshaler := MarshalerForRequest(s, r)
				s.cfg.errorHandler(ctx, s, outboundMarshaler, w, r, &HTTPStatusError{
					HTTPStatus: http.StatusBadRequest,
					Err:        mse,
				})
				return
			}
			continue
		}
		s.handleHandler(h, w, r, pathParams)
		return
	}

	// if no handler has found for the request, lookup for other methods
	// to handle POST -> GET fallback if the request is subject to path
	// length fallback.
	// Note we are not eagerly checking the request here as we want to return the
	// right HTTP status code, and we need to process the fallback candidates in
	// order to do that.
	// GET is tried first when the request is subject to path length fallback:
	// map iteration order is random, and a match for another method would
	// otherwise return 405 before the GET handler is reached.
	methods := make([]string, 0, len(s.handlers))
	if s.isPathLengthFallback(r) {
		methods = append(methods, http.MethodGet)
	}
	for m := range s.handlers {
		if m == http.MethodGet && s.isPathLengthFallback(r) {
			continue
		}
		methods = append(methods, m)
	}
	for _, m := range methods {
		if m == r.Method {
			continue
		}
		for _, h := range s.handlers[m] {
			var verb string
			patVerb := h.pat.Verb()

			idx := -1
			if patVerb != "" && strings.HasSuffix(lastPathComponent, ":"+patVerb) {
				idx = len(lastPathComponent) - len(patVerb) - 1
			}

			comps := pathComponents
			if idx > 0 {
				comps = make([]string, len(pathComponents))
				copy(comps, pathComponents)
				comps[len(comps)-1], verb = lastPathComponent[:idx], lastPathComponent[idx+1:]
			}

			pathParams, err := h.pat.matchAndEscape(comps, verb, unescapingMode, s.cfg.strictDeepWildcard)
			if err != nil {
				var mse MalformedSequenceError
				if ok := errors.As(err, &mse); ok {
					_, outboundMarshaler := MarshalerForRequest(s, r)
					s.cfg.errorHandler(ctx, s, outboundMarshaler, w, r, &HTTPStatusError{
						HTTPStatus: http.StatusBadRequest,
						Err:        mse,
					})
					return
				}
				continue
			}

			// X-HTTP-Method-Override is optional. Always allow fallback to POST.
			// Also, only consider POST -> GET fallbacks, and avoid falling back to
			// potentially dangerous operations like DELETE.
			if s.isPathLengthFallback(r) && m == http.MethodGet {
				if err := r.ParseForm(); err != nil {
					_, outboundMarshaler := MarshalerForRequest(s, r)
					sterr := status.Error(codes.InvalidArgument, err.Error())
					s.cfg.errorHandler(ctx, s, outboundMarshaler, w, r, sterr)
					return
				}
				s.handleHandler(h, w, r, pathParams)
				return
			}
			_, outboundMarshaler := MarshalerForRequest(s, r)
			s.cfg.routingErrorHandler(ctx, s, outboundMarshaler, w, r, http.StatusMethodNotAllowed)
			return
		}
	}

	_, outboundMarshaler := MarshalerForRequest(s, r)
	s.cfg.routingErrorHandler(ctx, s, outboundMarshaler, w, r, http.StatusNotFound)
}

// GetForwardResponseOptions returns the ForwardResponseOptions associated with this ServeMux.
func (s *ServeMux) GetForwardResponseOptions() []func(context.Context, http.ResponseWriter, proto.Message) error {
	return s.forwardResponseOptions
}

func (s *ServeMux) isPathLengthFallback(r *http.Request) bool {
	// The fallback switch only gates this implicit POST -> GET fallback. It
	// does not gate X-HTTP-Method-Override (see muxConfig.methodOverrideAllowed).
	return !s.cfg.disablePathLengthFallback && r.Method == http.MethodPost && isFormContentType(r)
}

type handler struct {
	pat Pattern
	h   HandlerFunc
	// raw is h before middlewares were applied.
	raw HandlerFunc
}

func (s *ServeMux) handleHandler(h handler, w http.ResponseWriter, r *http.Request, pathParams map[string]string) {
	h.h(w, r.WithContext(withHTTPPattern(r.Context(), h.pat)), pathParams)
}

func chainMiddlewares(mws []Middleware) Middleware {
	return func(next HandlerFunc) HandlerFunc {
		for i := len(mws); i > 0; i-- {
			next = mws[i-1](next)
		}
		return next
	}
}
